#!/usr/bin/env python3
"""Generate docs/ADLC.md — the skill library mapped to the AI development life cycle — from SKILL.md metadata.

Single source of truth: shared/adlc-stages.json (stages) + each skill's metadata.adlc_stage. Run after adding a skill:
    python3 scripts/gen_adlc_doc.py            # write docs/ADLC.md
    python3 scripts/gen_adlc_doc.py --check    # exit 1 if docs/ADLC.md is stale (CI)
"""
from __future__ import annotations
import argparse, json, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import skillmeta  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "ADLC.md"


def first_sentence(desc: str) -> str:
    d = " ".join(desc.split())
    if d.lower().startswith("use when"):
        d = d[len("use when"):].strip()
    cut = d.find(" — ") if " — " in d[:160] else d.find(". ")
    return (d[:cut] if 0 < cut < 160 else d[:157] + "…").rstrip(".")


def render() -> str:
    tax = json.loads((ROOT / "shared" / "adlc-stages.json").read_text(encoding="utf-8"))
    rows: dict[str, list[tuple[str, str]]] = {}
    for md in sorted(ROOT.glob("skills/*/*/SKILL.md")):
        sk = skillmeta.load_skill(md.parent)
        sid = f"{md.parent.parent.name}/{md.parent.name}"
        rows.setdefault(str(sk["metadata"].get("adlc_stage", "")), []).append((sid, first_sentence(str(sk.get("description", "")))))
    total = sum(len(v) for v in rows.values())
    adlc = sum(len(rows.get(s["id"], [])) for s in tax["stages"])
    lines = ["# Skills by AI development life cycle stage", "",
             f"Generated by `scripts/gen_adlc_doc.py` from `shared/adlc-stages.json` and each skill's `metadata.adlc_stage`. "
             f"{total} executable skills: {adlc} across {len(tax['stages'])} ADLC stages, {total - adlc} on business shelves. "
             "Every skill declares inputs, runs scripts, checks its outputs and ships eval cases.", "",
             "| # | Stage | Question it answers | Skills |", "|---|---|---|---|"]
    for s in tax["stages"]:
        names = ", ".join(f"`{sid.split('/')[1]}`" for sid, _ in rows.get(s["id"], [])) or "**gap**"
        lines.append(f"| {s['n']} | {s['name']} | {s['question']} | {names} |")
    for group in tax["stages"] + tax["shelves"]:
        items = rows.get(group["id"], [])
        if not items:
            continue
        title = f"{group['n']}. {group['name']}" if "n" in group else group["name"]
        lines += ["", f"## {title}", "", "| Skill | Use when |", "|---|---|"]
        lines += [f"| [`{sid}`](../skills/{sid}/SKILL.md) | {use} |" for sid, use in items]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if docs/ADLC.md is out of date")
    a = ap.parse_args()
    text = render()
    if a.check:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("docs/ADLC.md is up to date" if ok else "docs/ADLC.md is stale: run python3 scripts/gen_adlc_doc.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
