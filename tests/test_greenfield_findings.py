"""Pipeline fixes from the unattended greenfield batch (G1 API+Postgres, G2 student UI, G3 Supabase RLS)."""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("deliver_gf", REPO / "scripts" / "deliver.py")
d = importlib.util.module_from_spec(spec)
sys.modules["deliver_gf"] = d
spec.loader.exec_module(d)

HEADER = "id,title,files,acceptance,test,rollback\n"


def repo(tmp: Path) -> Path:
    (tmp / "app").mkdir(parents=True)
    (tmp / "app" / "page.tsx").write_text("export default function P() { return null }\n", encoding="utf-8")
    return tmp


def test_stack_convention_directories_are_not_invented_layout(tmp_path):
    """G1 named server/services/*.ts and G3 supabase/migrations/*.sql; both were refused before any code was written."""
    t = repo(tmp_path / "r")
    tasks = tmp_path / "tasks.csv"
    tasks.write_text(HEADER + "T1,a,server/services/enroll.ts;supabase/migrations/0001_init.sql;tests/unit/enroll.test.ts,x,y,z\n", encoding="utf-8")
    assert d.Run.plan_fits_repo(str(tasks), t, {"flavour": "ts"}) == []


def test_an_invented_src_layout_is_still_refused(tmp_path):
    t = repo(tmp_path / "r")
    tasks = tmp_path / "tasks.csv"
    tasks.write_text(HEADER + "T1,a,src/app/page.tsx,x,y,z\n", encoding="utf-8")
    assert any("invented layout" in p for p in d.Run.plan_fits_repo(str(tasks), t, {"flavour": "ts"}))


def test_unfilled_scaffold_stubs_are_found_and_filled_ones_are_not(tmp_path):
    """G2: "56 passed, 11 skipped" passed the gate with 11 scaffold files still all it.todo."""
    u = tmp_path / "tests" / "unit"
    u.mkdir(parents=True)
    hdr = "// Red first: generated by test-strategy-tdd for lib/x.ts. Replace each todo with a failing test.\n"
    (u / "stub.test.ts").write_text(hdr + 'it.todo("shows progress");\n', encoding="utf-8")
    (u / "filled.test.ts").write_text(hdr + 'it("shows progress", () => { expect(1).toBe(1) });\n', encoding="utf-8")
    (u / "own.test.ts").write_text('it.todo("someone else\'s todo, not the scaffold\'s");\n', encoding="utf-8")
    (tmp_path / "e2e").mkdir()
    (tmp_path / "e2e" / "flow.spec.ts").write_text("// Red first: generated by test-strategy-tdd for app/page.tsx. Replace each fixme with a real flow.\ntest.fixme('flow', async () => {});\n", encoding="utf-8")
    assert d.Run.unfilled_test_stubs(tmp_path) == ["tests/unit/stub.test.ts", "e2e/flow.spec.ts"] or \
           sorted(d.Run.unfilled_test_stubs(tmp_path)) == ["e2e/flow.spec.ts", "tests/unit/stub.test.ts"]
