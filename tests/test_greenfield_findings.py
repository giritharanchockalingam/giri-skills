import subprocess  # noqa: E402

SCAN = REPO / "skills/build/security-review/scripts/scan.py"
ACTION = ('"use server";\nimport { getSessionUser } from "@/server/services/auth";\n'
          'export async function addNote(form: FormData) {\n  const u = await getSessionUser();\n  return u;\n}\n')


def sec1(tmp: Path, helper_body: str) -> list[str]:
    (tmp / "app" / "notes").mkdir(parents=True)
    (tmp / "server" / "services").mkdir(parents=True)
    (tmp / "app" / "notes" / "actions.ts").write_text(ACTION, encoding="utf-8")
    (tmp / "server" / "services" / "auth.ts").write_text(helper_body, encoding="utf-8")
    subprocess.run([sys.executable, "-I", str(SCAN), "--target", str(tmp), "--findings", str(tmp / "f.csv"), "--report", str(tmp / "r.md")],
                   capture_output=True, text=True, cwd=tmp)
    return [ln for ln in (tmp / "f.csv").read_text(encoding="utf-8").splitlines() if ",authz," in ln]


def test_sec1_sees_an_auth_check_one_import_away(tmp_path):
    """G3: getSessionUser() wraps supabase.auth.getUser() in server/services/auth.ts; the action is authenticated."""
    helper = "export async function getSessionUser(client) {\n  const { data } = await client.auth.getUser();\n  return data.user;\n}\n"
    assert sec1(tmp_path, helper) == []


def test_sec1_still_flags_a_helper_that_checks_nothing(tmp_path):
    helper = "export async function getSessionUser() {\n  return { id: 'anyone' };\n}\nexport function other() { return auth.getUser(); }\n"
    assert len(sec1(tmp_path, helper)) == 1      # the auth call in a DIFFERENT function does not count
