#!/usr/bin/env python3
"""Generate RLS policies from the RBAC matrix — one policy per action × role.

    python3 -I scripts/rbac_to_sql.py assets/rbac-matrix.csv --out policies.sql [--schema public] [--owner-column created_by]

Input: the assets/rbac-matrix.csv layout — action (`<entity>.<verb>`), resource (table), one column
per role (viewer, member, admin, owner … value allow | deny | own), enforcement_rls (policy name
stem or `n/a …`), enforcement_service, ui, audited. Verb → operation: read/list/view/export/get →
select; create/invite/upload/add → insert; update/change_*/void/toggle/edit/set → update;
delete/remove → delete. Rows whose enforcement_rls starts with `n/a` are emitted as comments
(service-only paths). JWT convention from references/tenant-model.md: tenant and role come from
`auth.jwt() -> 'app_metadata'`; `own` adds `<owner-column> = auth.uid()`. Writes policies.sql with
`-- rollback:` drop statements. Exit 1 on missing file, missing columns or no allow/own cell. Stdlib.
"""
from __future__ import annotations

import argparse
import csv
import re
import sys
from pathlib import Path

NON_ROLE = {"action", "resource", "enforcement_rls", "enforcement_service", "ui", "audited"}
OPS = [("select", ("read", "list", "view", "export", "get", "search")),
       ("insert", ("create", "invite", "upload", "add", "import")),
       ("update", ("update", "change", "void", "toggle", "edit", "set", "rename", "archive", "transfer")),
       ("delete", ("delete", "remove"))]
TENANT = "(select (auth.jwt() -> 'app_metadata' ->> 'tenant_id'))::uuid"
ROLE = "(select auth.jwt() -> 'app_metadata' ->> 'role')"


def die(msg: str) -> None:
    print(f"error: {msg}", file=sys.stderr)
    sys.exit(1)


def op_for(action: str) -> str | None:
    verb = action.split(".", 1)[-1].lower()
    for op, verbs in OPS:
        if any(verb == v or verb.startswith(v + "_") for v in verbs):
            return op
    return None


def ident(s: str) -> str:
    s = re.sub(r"[^a-z0-9_]+", "_", s.lower()).strip("_")
    return s[:63]


def main() -> int:
    ap = argparse.ArgumentParser(description="RBAC matrix CSV -> RLS policies SQL")
    ap.add_argument("matrix", help="rbac-matrix.csv")
    ap.add_argument("--out", default="policies.sql")
    ap.add_argument("--schema", default="public")
    ap.add_argument("--owner-column", default="created_by", help="column compared to auth.uid() for `own`")
    ap.add_argument("--tenant-table", default="tenants", help="the tenants table itself, where the tenant column is `id`")
    a = ap.parse_args()
    p = Path(a.matrix)
    if not p.is_file():
        die(f"matrix not found: {p}")
    rows = [r for r in csv.DictReader(p.open(encoding="utf-8-sig"))
            if not (r.get("action") or "").strip().startswith("#")]   # a leading `#` row is a fixture/comment note
    if not rows:
        die("matrix has no rows")
    header = list(rows[0].keys())
    for col in ("action", "resource"):
        if col not in header:
            die(f"matrix lacks column '{col}' (expected the assets/rbac-matrix.csv layout)")
    roles = [h for h in header if h and h not in NON_ROLE]
    if not roles:
        die("matrix has no role columns")

    out = [f"-- policies.sql — generated by multi-tenant-saas-patterns/scripts/rbac_to_sql.py from {p.name}",
           f"-- Convention: tenant and role are read from the JWT app_metadata claims (references/tenant-model.md);",
           f"-- `own` rows compare {a.owner_column} with auth.uid(). One policy per action × role. Review before applying;",
           "-- hand to supabase-schema-rls for the migration (with its rollback block) and rls_lint.py.", ""]
    rollback, n_pol, skipped, unmapped = [], 0, [], []
    for r in rows:
        action, table = r["action"].strip(), ident(r["resource"].strip().split(".")[-1])
        if not action or not table:
            continue
        rls = (r.get("enforcement_rls") or "").strip()
        if rls.lower().startswith("n/a"):
            skipped.append(action)
            out.append(f"-- {action}: no RLS policy ({rls}); enforced in service: {r.get('enforcement_service', '')}")
            continue
        op = op_for(action)
        if not op:
            unmapped.append(action)
            out.append(f"-- {action}: verb not mapped to an operation — write this policy by hand")
            continue
        for role in roles:
            cell = (r.get(role) or "").strip().lower()
            if cell not in ("allow", "own"):
                continue
            name = ident(f"{rls or table + '_' + op}_{role}")
            tcol = "id" if table == ident(a.tenant_table) else "tenant_id"
            pred = f"{tcol} = {TENANT} and {ROLE} = '{role}'"
            if cell == "own":
                pred += f" and {a.owner_column} = (select auth.uid())"
            clause = f"with check ({pred})" if op == "insert" else f"using ({pred})" + (f"\n  with check ({pred})" if op == "update" else "")
            out.append(f"-- {action} / {role}: {cell}" + (f"; audited" if (r.get('audited') or '').strip().lower() == 'yes' else ""))
            out.append(f"create policy {name} on {a.schema}.{table}\n  for {op} to authenticated\n  {clause};")
            out.append("")
            rollback.append(f"-- drop policy if exists {name} on {a.schema}.{table};")
            n_pol += 1
    if n_pol == 0:
        die("no allow/own cells found — nothing to generate")
    out += ["-- rollback:"] + rollback
    outp = Path(a.out)
    outp.parent.mkdir(parents=True, exist_ok=True)
    outp.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{n_pol} policies for {len(rows)} action(s) across roles {roles}; {len(skipped)} service-only, "
          f"{len(unmapped)} unmapped -> {outp}")
    if unmapped:
        print(f"warning: unmapped verbs: {unmapped}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
